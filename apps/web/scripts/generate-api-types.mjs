import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import prettier from "prettier";

/**
 * Generates lib/api.types.generated.ts from docs/openapi.yaml with
 * openapi-typescript (issue #599). CI runs this with --check so hand-written
 * types cannot drift from the spec unnoticed.
 */
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "../../..");
const sourcePath = resolve(repositoryRoot, "docs/openapi.yaml");
const outputPath = resolve(scriptDirectory, "../lib/api.types.generated.ts");

const source = await readFile(sourcePath, "utf8");
const ast = await openapiTS(source);
const generated = await prettier.format(
  `// Generated by scripts/generate-api-types.mjs from docs/openapi.yaml.
// Do not edit by hand; run \`pnpm openapi:generate\` instead.

${astToString(ast)}`,
  { filepath: outputPath }
);

if (process.argv.includes("--check")) {
  let current;
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    throw new Error(
      "Generated API types are missing; run pnpm openapi:generate"
    );
  }
  if (current !== generated) {
    throw new Error("Generated API types are stale; run pnpm openapi:generate");
  }
} else {
  await writeFile(outputPath, generated);
}
