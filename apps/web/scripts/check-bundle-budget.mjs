#!/usr/bin/env node
/**
 * Bundle budget check (issue #614).
 *
 * Runs against a production build (pnpm build) and fails when any route's
 * first-load JavaScript, or the total shipped client JS, exceeds the
 * budgets in apps/web/performance-budget.json. Sizes are gzipped — what
 * the browser actually downloads over the wire.
 *
 * Usage:
 *   node scripts/check-bundle-budget.mjs                 # enforce budgets
 *   node scripts/check-bundle-budget.mjs --update-baseline # rewrite the
 *                         # budgets from the current build (+10% headroom)
 *
 * See docs/performance.md for how the budgets are maintained.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);
const nextDir = path.join(webRoot, ".next");
const budgetPath = path.join(webRoot, "performance-budget.json");

const updateBaseline = process.argv.includes("--update-baseline");

const manifestPath = path.join(nextDir, "app-build-manifest.json");
if (!existsSync(manifestPath)) {
  console.error(
    "No .next/app-build-manifest.json found. Run `pnpm build` first."
  );
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const budget = updateBaseline
  ? null
  : JSON.parse(readFileSync(budgetPath, "utf8"));

/** Gzipped size of a build output file, in bytes. */
function gzipSize(relFile) {
  const abs = path.join(nextDir, relFile);
  if (!existsSync(abs)) return 0;
  return gzipSync(readFileSync(abs)).length;
}

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

// Per-route first-load JS: every .js file the route's entry needs,
// deduplicated (shared chunks are counted once per route, not once per
// reference). CSS and other assets are ignored.
const routeSizes = {};
for (const [route, files] of Object.entries(manifest.pages ?? {})) {
  const jsFiles = new Set(files.filter((f) => f.endsWith(".js")));
  routeSizes[route] = [...jsFiles].reduce((sum, f) => sum + gzipSize(f), 0);
}

// Total client JS shipped under static/chunks — the ceiling on what any
// session can end up downloading.
const chunksDir = path.join(nextDir, "static", "chunks");
let totalStaticJs = 0;
if (existsSync(chunksDir)) {
  const { readdirSync, statSync } = await import("node:fs");
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const abs = path.join(dir, entry);
      if (statSync(abs).isDirectory()) walk(abs);
      else if (entry.endsWith(".js"))
        totalStaticJs += gzipSync(readFileSync(abs)).length;
    }
  };
  walk(chunksDir);
}

const routes = Object.keys(routeSizes).sort();

if (updateBaseline) {
  const headroom = 1.1;
  const next = {
    comment:
      "Generated by `node scripts/check-bundle-budget.mjs --update-baseline`: current build sizes + 10% headroom.",
    maxRouteFirstLoadJsBytes: Object.fromEntries(
      routes.map((r) => [
        r,
        Math.ceil((routeSizes[r] * headroom) / 1024) * 1024,
      ])
    ),
    maxTotalStaticJsBytes: Math.ceil((totalStaticJs * headroom) / 1024) * 1024,
  };
  writeFileSync(budgetPath, `${JSON.stringify(next, null, 2)}\n`);
  console.log(`Baselines written to ${path.relative(webRoot, budgetPath)}:`);
  for (const r of routes) console.log(`  ${r}: ${kb(routeSizes[r])}`);
  console.log(`  total static JS: ${kb(totalStaticJs)}`);
  process.exit(0);
}

// ---- Enforce ----------------------------------------------------------------

const violations = [];
const pad = (s, n) => s.padEnd(n, " ");

console.log("Route first-load JS (gzipped) vs budget:");
for (const route of routes) {
  const limit =
    budget.maxRouteFirstLoadJsBytes?.[route] ??
    budget.maxRouteFirstLoadJsBytes?.["*"];
  const size = routeSizes[route];
  if (limit === undefined) {
    console.log(`  ${pad(route, 40)} ${kb(size).padStart(10)}   (no budget)`);
  } else if (size > limit) {
    violations.push(
      `${route}: ${kb(size)} exceeds the ${kb(limit)} first-load JS budget`
    );
    console.log(
      `  ${pad(route, 40)} ${kb(size).padStart(10)} > ${kb(limit).padStart(9)}  FAIL`
    );
  } else {
    console.log(
      `  ${pad(route, 40)} ${kb(size).padStart(10)} <= ${kb(limit).padStart(9)}  ok`
    );
  }
}

const totalLimit = budget.maxTotalStaticJsBytes;
if (totalLimit !== undefined) {
  const ok = totalStaticJs <= totalLimit;
  console.log(
    `  ${pad("total static JS", 40)} ${kb(totalStaticJs).padStart(10)} ${
      ok ? "<=" : ">"
    } ${kb(totalLimit).padStart(9)}  ${ok ? "ok" : "FAIL"}`
  );
  if (!ok)
    violations.push(
      `total static JS ${kb(totalStaticJs)} exceeds the ${kb(totalLimit)} budget`
    );
}

if (violations.length > 0) {
  console.error(`\n${violations.length} budget violation(s):`);
  for (const v of violations) console.error(`  - ${v}`);
  console.error(
    "\nIf the growth is intentional, re-baseline with\n  node scripts/check-bundle-budget.mjs --update-baseline\nand commit the updated performance-budget.json with your change."
  );
  process.exit(1);
}

console.log("\nAll bundle budgets respected.");
