-- Indexer transaction retry table.
-- When fetchWindow fails to fetch a transaction after exhausting retries, the tx hash is
-- parked here so the invocation is not permanently lost when the cursor advances.
-- A background requeue path can retry these rows later.

CREATE TABLE IF NOT EXISTS indexer_tx_retry (
	id            BIGSERIAL PRIMARY KEY GENERATED BY DEFAULT,
	network        TEXT NOT NULL,
	tx_hash       TEXT NOT NULL,
	contract_id   TEXT NOT NULL,
	ledger         BIGINT NOT NULL,
	attempts       INTEGER NOT NULL DEFAULT 0,
	last_error     TEXT NOT NULL DEFAULT '',
	status         TEXT NOT NULL DEFAULT 'pending', -- pending | requeued | resolved
	created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	requeued_at    TIMESTAMPTZ
);

-- Prevent duplicate parking of the same tx hash for a network.
-- A tx hash is unique per network, and repeated failures should bump attempts instead
-- of inserting new rows.
CREATE UNIQUE,INDEX if_not_exists indexer_tx_retry_network_tx_hash_key
	ON indexer_tx_retry (network, tx_hash);

-- Support requeue worker scans by status and age.
CREATE INDEX if_not_exists indexer_tx_retry_status_idx
	ON indexer_tx_retry (status, created_at);
