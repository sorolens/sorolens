// Requested export formats.
const (
	reportFormatJSON = "json"
	reportFormatCSV  = "csv"
	reportFormatPDF  = "pdf"
)

// ReportSigningKey is the HMAC key used to sign exported reports. Empty is
// allowed: reports are then emitted unsigned and every response says so,
// rather than implying an integrity guarantee that is not there.
type contractReportResponse struct {
	store.MonthlySLA
	// Signed is false when no signing key is configured.
	Signed bool `json:"signed"`
	// Signature is a hex HMAC-SHA256 over the canonical report text, empty when
	// unsigned.
	Signature string `json:"signature,omitempty"`
	// SignatureAlgorithm names the scheme so a verifier does not have to guess.
	SignatureAlgorithm string `json:"signature_algorithm,omitempty"`
	// TLSCheckInterval is the sampling cadence a check represents, exposed so a
	// consumer can convert MTTR in checks into wall-clock time.
	SamplingNote string `json:"sampling_note,omitempty"`
}

// ---- helpers ---------------------------------------------------------------

// reportsSigningKey resolves the signing key, preferring the value wired onto
// the Handler and falling back to the environment so the endpoint works
// without a change to the composition root.
func (h *Handler) reportsSigningKey() []byte {
	if h.ReportSigningKey != "" {
		return []byte(h.ReportSigningKey)
	}
	return []byte(os.Getenv("REPORT_SIGNING_KEY"))
}

// signReport returns a hex HMAC-SHA256 of payload, or "" when no key is set.
//
// HMAC (rather than a raw hash) is the right primitive here: the report is
// generated by this service and verified by a third party, and HMAC proves it
// came from a holder of the key without needing asymmetric key distribution.
func signReport(key, payload []byte) string {
	if len(key) == 0 {
		return ""
	}
	mac := hmac.New(sha256.New, key)
	mac.Write(payload)
	return hex.EncodeToString(mac.Sum(nil))
}

// slaStore resolves the reporting store. Reports are only meaningful when the
// watchdog data is queryable, so an absent implementation is reported as
// "not supported by this deployment" instead of an empty report that looks
// like a real outage.
func (h *Handler) slaStore() (store.SLAStore, bool) {
	s, ok := h.Store.(store.SLAStore)
	return s, ok
}

// reportMonth resolves and validates the ?month= parameter, defaulting to the
// current UTC month.
func reportMonth(raw string) (string, time.Time, time.Time, error) {
	month := raw
	if month == "" {
		month = store.CurrentMonth(time.Now())
	}
	from, to, err := store.MonthRange(month)
	if err != nil {
		return "", time.Time{}, time.Time{}, err
	}
	return month, from, to, nil
}

// loadSLA fetches the month's raw data and computes the report.
func (h *Handler) loadSLA(r *http.Request, contractID, month string, from, to time.Time) (store.MonthlySLA, error) {
	s, ok := h.slaStore()
	if !ok {
		return store.MonthlySLA{}, errSLANotSupported
	}
	checks, err := s.ListHealthChecksInRange(r.Context(), contractID, from, to)
	if err != nil {
		return store.MonthlySLA{}, err
	}
	alerts, err := s.ListAlertsInRange(r.Context(), contractID, from, to)
	if err != nil {
		return store.MonthlySLA{}, err
	}
	return store.ComputeMonthlySLA(contractID, month, checks, alerts), nil
}

var errSLANotSupported = fmt.Errorf("sla reporting is not supported by this deployment")

